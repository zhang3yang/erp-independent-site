-- =====================================================================
-- 迁移台账：记录这个库跑过哪些迁移脚本
-- =====================================================================
--
-- 起因：2026-09-08 做本地/线上对账时发现，sql/station/migration/ 下已经攒了
-- 10 个脚本，而库里没有任何地方记录跑过哪几个。当时只能把
-- information_schema.columns 整个拉下来、和 01_station_schema.sql 逐列比对，
-- 才敢说"对齐了"。
--
-- 脚本本身都写了幂等，所以"不确定跑没跑就再跑一遍"是安全的——这也是为什么
-- 缺了台账这么久也没出事。但它解决不了另外两个问题：
--
--   · 新装一台机器时，没人知道该跑哪几个、按什么顺序；
--   · 某个脚本"跑了一半失败了"和"根本没跑"，现象完全一样。
--
-- =====================================================================
-- 这张表不做什么
-- =====================================================================
--
-- 它**不是** Flyway/Liquibase，没有校验和、不阻止乱序、不会自动执行任何东西。
-- 就是一张人工登记表：跑完一个脚本，自己插一行。
--
-- 之所以不上 Flyway：这个库一共 17 张表，迁移脚本一个月 10 个，
-- 引入一个框架要连带管住"基线怎么打、已存在的库怎么 baseline、
-- 校验和对不上时怎么办"，成本比它解决的问题大。等真的多站多机了再说。
--
-- ⚠ 所以它的准确性靠人。跑脚本忘了登记，台账就是错的——而错的台账
--   比没有台账更危险，因为下一个人会信它。宁可插一行"不确定"，也别不插。
--
-- =====================================================================
-- 可重复执行：CREATE TABLE IF NOT EXISTS + INSERT IGNORE。
-- =====================================================================

USE `sdsstation`;

CREATE TABLE IF NOT EXISTS `u_s_schema_migration` (
  `filename`  varchar(200) NOT NULL COMMENT '脚本文件名，和 sql/station/migration/ 下的文件名一字不差。用它做主键而不是自增 id：重复登记同一个脚本应该失败，而不是产生第二行',
  `appliedat` datetime     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '登记时间。source=回填时，这是回填的时间，不是脚本实际执行的时间',
  `appliedby` varchar(50)           DEFAULT NULL COMMENT '谁跑的',
  `source`    varchar(20)  NOT NULL DEFAULT '执行' COMMENT '⚠ 这一列是这张表最重要的部分。执行=确实跑过这个脚本；回填=没有执行记录，只是按结构比对确认它的改动已经在库里生效了。两者的可信度不一样，不能混着看',
  `note`      varchar(500)          DEFAULT NULL COMMENT '备注。回填的要写清依据',
  PRIMARY KEY (`filename`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='迁移台账，人工登记';


