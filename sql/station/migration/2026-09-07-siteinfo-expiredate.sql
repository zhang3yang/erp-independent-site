-- =====================================================================
-- 给 u_s_siteinfo 加 expiredate：让管理台首页那个「服务到期」统计块真的有数
-- =====================================================================
--
-- 这不是新功能，是补一个从拆分上线起就一直空着的洞。
--
-- 管理台首页 Overview.vue 第四个统计块引用 site.expireDate / site.expireDays，
-- 而独立站这边的 u_s_siteinfo 根本没有这一列，/site 接口也从没下发过这两个字段。
-- 那段代码是从「ERP 内置管理台」那一版搬过来的——那时候整个 site 对象来自 ERP、
-- 自带到期日；搬到独立部署之后数据源没跟过来，代码却留着。
--
-- ⚠ 它的表现是「未设置到期日」，看上去只像是这个站没填，而不像功能坏了。
--   所以这个洞在线上挂了很久没人报。
--
-- =====================================================================
-- 和 ERP 那份 expiredate 的关系：没有关系
-- =====================================================================
--
-- ERP 的 sdsshop.u_s_site 里也有 expiredate。两份**不同步**，和域名是同一回事：
-- 两个库两台机器，中间没有任何通道（docs/独立站与ERP的边界.md 要点 1）。
--
--   · ERP 那份是我们自己的收费台账。独立站列表按剩余天数排序，快到期的顶上来，
--     用来提醒我们去续费催款；
--   · 这一份是站长在自己管理台上看的。
--
-- 在 ERP 里改到期日，这边不会变，反之亦然。两边都要准的话，两边都得改。
--
-- =====================================================================
-- 剩余天数为什么不落库
-- =====================================================================
--
-- ERP 那边是 `datediff(expiredate, curdate()) expiredays` 现算的。这边不能照抄：
-- SiteInfoService 把站点档案**缓存在进程里**，只在写操作之后失效，而站点档案
-- 几个星期不写一次很正常。SQL 算出来的天数会连同对象一起冻在加载那一刻——
-- 页面上「还有 30 天到期」挂着不动，真过期了也不变红，而这块提醒的全部价值
-- 就是那个会走的数字。所以放在 Java 里现算：SiteInfo#getExpireDays()。
--
-- =====================================================================
-- 什么时候需要跑这一份
-- =====================================================================
--
-- 只在「库是这次改动之前建的」时候需要。
-- sql/station/01_station_schema.sql 里已经带上这一列了，新建的库不用跑。
--
-- 和同目录下 2026-09-08-currency-rate.sql 相互独立，谁先谁后都行。
--
-- 幂等：重复执行不报错（下面用了 information_schema 判断）。
-- =====================================================================

SET @has_col := (
  SELECT COUNT(*) FROM information_schema.COLUMNS
   WHERE TABLE_SCHEMA = DATABASE()
     AND TABLE_NAME   = 'u_s_siteinfo'
     AND COLUMN_NAME  = 'expiredate'
);

SET @ddl := IF(@has_col > 0,
  'SELECT ''u_s_siteinfo.expiredate 已存在，跳过'' AS msg',
  'ALTER TABLE `u_s_siteinfo`
     ADD COLUMN `expiredate` date DEFAULT NULL
     COMMENT ''服务到期日，null=不提醒。剩余天数由 SiteInfo.getExpireDays() 现算，不落库。⚠ 与 ERP 的 u_s_site.expiredate 不同步''
     AFTER `status`');

PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;


-- ---------------------------------------------------------------------
-- 加完是 NULL，也就是「不提醒」，统计块继续显示「未设置」——这是安全的落点，
-- 不要在这里塞一个猜的日期。
--
-- 真正的到期日在 ERP 的独立站档案里，照着填过来：
--
--   UPDATE `u_s_siteinfo` SET `expiredate` = '2026-12-04' WHERE `id` = 1;
--
-- 也可以直接在管理台「站点设置」里选，不用跑 SQL。
--
-- ⚠ 改完库要重启 station-console：档案缓存在进程里，绕过服务改库不会让它失效。
--    从管理台改则不需要，那条路会自己清缓存。
-- ---------------------------------------------------------------------
