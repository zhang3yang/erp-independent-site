-- =====================================================================
-- 站点分类的多语言显示名
-- 2026-09-20
-- =====================================================================
--
-- 在这之前，前台产品页侧栏的分类**三种语言显示的文字完全一样**：
--
--     中文页 / 英文页 / 日文页都是
--         BATTERIES / CABLE ASSEMBLIES / PUMPS / SILICONE PARTS / 加压疗法 > 腿部系统
--
-- 因为 u_s_sitegoods.sitecategory 是主表上的一列自由文本，一份数据供所有语言共用。
--
-- 本次加一张表存各语言的显示名。译名由后端照默认语言自动翻（保存商品时补齐、
-- 管理台也能一键补齐），翻歪了在管理台「分类译名」那张表里手工改。
--
-- ---------------------------------------------------------------------
-- ⚠ catkey 存的是「路径的每一级」，不是整串
-- ---------------------------------------------------------------------
--
-- 分类 `加压疗法/腿部系统` 拆成两行：
--
--     catkey = '加压疗法'               lang = 'ja'   name = '圧迫療法'
--     catkey = '加压疗法/腿部系统'       lang = 'ja'   name = 'レッグシステム'
--
-- 为什么不整串译一次：大组「加压疗法」下面挂 5 个子分类的话，整串译就要把
-- 「圧迫療法」这四个字在 5 行里各翻一遍、各存一遍，很可能翻出 5 种不同写法，
-- 侧栏的组标题就飘了。逐级存则大组只翻一次，所有子分类共用。
--
-- 为什么用完整前缀而不是光秃秃的一段：`腿部系统` 可能同时挂在两个大组下，
-- 语义未必相同。用前缀让每个节点有唯一身份。
--
-- ---------------------------------------------------------------------
-- ⚠ 主表 u_s_sitegoods.sitecategory 一个字都不改
-- ---------------------------------------------------------------------
--
-- 那一列继续同时充当三件事：筛选键（URL 的 ?cat=、SiteGoodsMapper 的前缀子树匹配）、
-- 两级层次的载体（靠分隔符 / ／ > ＞）、以及没有译名时的兜底显示文字。
-- 本表只接管「显示文字」这一件。
--
-- 这么分的好处是 **URL 永远是原串，切语言不断链**——否则日文页的链接带着日文分类名，
-- 切回中文就筛不出东西了。
--
-- ---------------------------------------------------------------------
-- 只存非默认语言
-- ---------------------------------------------------------------------
--
-- 默认语言的显示名就是 catkey 的最后一段原文，存一份完全一样的进来没有意义，
-- 还会多出一份可能和原文不同步的数据。前台查不到译名就显示原文，天然正确。
--
-- ⚠ 线上库 sdsstation，用 mysql 客户端跑的话记得 --default-character-set=utf8mb4，
--   见 memory/mysql-cli-charset-gbk。
-- =====================================================================

create table if not exists `u_s_sitecategory_lang` (
  `shop_code`  varchar(50)  not null default '' comment '【遗留列】恒为建站时那个商户码，不参与过滤',
  `sitecode`   varchar(50)  not null comment '站点编码，恒等于 u_s_siteinfo.sitecode',
  `catkey`     varchar(100) not null comment '分类路径的一级，取完整前缀。如 加压疗法、加压疗法/腿部系统。⚠ 不是整串译，见文件头',
  `lang`       varchar(20)  not null comment '语言代码，如 en / ja / ko。⚠ 只存非默认语言：默认语言直接用 catkey 最后一段原文',
  `name`       varchar(100) default null comment '该语言下的显示名。空或没有这一行 → 前台显示 catkey 最后一段原文，绝不会出现空标签',
  `createtime` datetime     not null default current_timestamp comment '创建时间',
  `updatetime` datetime     default current_timestamp on update current_timestamp comment '更新时间',
  primary key (`shop_code`,`sitecode`,`catkey`,`lang`)
) engine=innodb default charset=utf8mb4 collate=utf8mb4_0900_ai_ci
  comment='站点分类的多语言显示名。行的来源是 u_s_sitegoods.sitecategory 按分隔符逐级拆出来的前缀；没有商品挂着的分类不会出现在前台，孤儿行只是躺着';
