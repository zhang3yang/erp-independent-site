-- =====================================================================
-- u_s_site.buyerdomain 改回「买家中心域名」
-- =====================================================================
--
-- 库：sdsshop（ERP 那台）。可重复执行。
--
-- ⚠ 这个脚本**只改列注释，不改数据、不改结构**。不跑它功能也是好的
--   （代码那边已经改完了）；跑它只是让线上库里的注释别继续误导下一个人。
--
-- =====================================================================
-- 这一列的说明反复过两次，这是第三次，写清楚免得还有第四次
-- =====================================================================
--
--   设计期      「买家后台域名，一期只登记、不实现」
--               想法是：前台挂主域，buyer. 子域留给以后的买家中心。
--
--   2026-09-07  改成「前台域名（访客看到的站）」
--               见 20260907_site_buyerdomain_is_front.sql。理由是实际部署时
--               主域在 nginx 上连 server 块都没有，前台落在了 buyer. 子域上，
--               买家中心是它下面的几个页面而不是另一个站。
--
--   2026-09-08  改回「买家中心域名」← 本脚本
--               用户要求「登录的人和浏览的人不在同一个域名上」。于是：
--                 商城（首页、商品、购物车、下单、登录注册）  → 主域
--                 买家中心（我的订单、账号资料、地址簿管理）  → buyer. 子域
--               主域可以对外服务，备案覆盖得到（2026-09-08 确认）。
--
-- 也就是绕了一圈回到设计期的原意。中间那一版不是拍脑袋，是当时部署条件下的
-- 唯一选择——主域打不开，前台只能落在子域上。
--
-- 设计和实施计划：
--   docs/设计稿/2026-09-08-独立站域名拆分.md
--   docs/设计稿/2026-09-08-独立站域名拆分实施计划.md
--
-- =====================================================================
-- ⚠ 不用改数据
-- =====================================================================
--
-- 两个站的 buyerdomain 都是空的，派生规则（buyer.<主域名>）直接给出正确结果。
-- 只有客户自带品牌域名、不照 buyer. 约定命名时，才需要在站点登记页填这一列。
--
-- 而站点登记列表上那个「前台地址」链接现在由 StationSite#getFrontUrl 拼，
-- 走的是**主域名**那一列，不再走这一列。
--
-- =====================================================================
-- 执行
-- =====================================================================
--   mysql -h 82.156.158.174 -uroot -p --default-character-set=utf8mb4 < 本文件
--   本机同样跑一遍
-- =====================================================================

USE `sdsshop`;

-- MODIFY COLUMN 要把列定义整段重写一遍，漏掉的属性会被丢掉——
-- 这里和 01_schema_and_init.sql 里那一行保持逐字一致，只有 COMMENT 不同。
ALTER TABLE `u_s_site`
  MODIFY COLUMN `buyerdomain` varchar(200) DEFAULT NULL
  COMMENT '买家中心域名（登录后的我的订单、账号资料、地址簿）。留空则取 buyer.<主域名>。⚠ 这不是前台——前台（商城）在主域上，站点登记列表那个链接由主域名拼，见 StationSite#getFrontUrl';


-- =====================================================================
-- 验一遍
-- =====================================================================

SELECT COLUMN_NAME AS `列`, COLUMN_COMMENT AS `注释`
  FROM information_schema.COLUMNS
 WHERE TABLE_SCHEMA = 'sdsshop'
   AND TABLE_NAME   = 'u_s_site'
   AND COLUMN_NAME  = 'buyerdomain';
