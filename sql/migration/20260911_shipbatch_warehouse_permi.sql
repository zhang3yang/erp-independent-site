-- 仓库发货页拆出独立权限串，库管员不必再跨树勾权限（2026-09-11）。可重复执行。
--
-- ============================================================================
-- 起因：为了让库管员看到全部批次，得给他一个订单管理菜单
-- ============================================================================
--
-- 「库存管理 → 仓库发货管理」(fn5103) 和「订单管理 → 发货批次」(fn8010) 用的是
-- 同一个 /order/shipbatch/list 接口，原先<b>连权限串都是同一个</b>
-- （order:shipbatch:list），系统分不出「这人是仓库还是销售」。
--
-- 于是横向权限只能另开一个开关 order:shipbatch:all，而它挂在订单管理树下。
-- 结果配一个库管员角色要这样：
--
--     库存管理 → 仓库发货管理          ← 他该有的
--     订单管理 → 发货批次 → 查看全部…  ← 为了看全部批次不得不勾
--
-- 而角色表单的「父子联动」默认是开的，勾最后那一项会连带勾上父节点，
-- 库管员的侧边栏就多出一个「订单管理」——看着像权限越界，实际他也用不上。
--
-- ============================================================================
-- 改法：仓库发货页用自己的权限串，持有它就等于能看全部批次
-- ============================================================================
--
--     fn5103  仓库发货管理   order:shipbatch:list  →  order:shipbatch:warehouse
--
-- 「能进仓库发货页」和「只看得到自己建的批次」本来就分不开：这个页面的全部工作内容
-- 就是处理别人建的批次，库管员自己不建批次，只看自己的等于工作台永远是空的。
-- 既然分不开，就别让它可配——由权限串本身表达。
--
-- 改完之后库管员角色只勾库存管理这一棵树就够了，订单管理一项都不用给。
--
-- order:shipbatch:all（fn8043）保留，现在它只管「订单管理 → 发货批次」那个页面
-- ——业务主管想在那儿看全店排产时才勾。菜单名去掉「（库管员必选）」，
-- 库管员已经不需要它了。
--
-- ============================================================================
-- ⚠ 必须和代码一起发布
-- ============================================================================
--
-- ShipBatchController 的 /list 鉴权同步改成
--   @ss.hasAnyPermi('order:shipbatch:list,order:shipbatch:warehouse')
--
-- 只跑 SQL 不发代码：只有 fn5103 没有 fn8010 的角色会拿不到 order:shipbatch:list，
-- 仓库发货页直接 403。
-- 只发代码不跑 SQL：fn5103 还是老权限串，库管员照旧只看得到自己建的批次。
--
-- ============================================================================
-- 执行
-- ============================================================================
--   mysql -h 127.0.0.1      -uroot -p --default-character-set=utf8mb4 < 20260911_shipbatch_warehouse_permi.sql
--   mysql -h 124.221.220.89 -uroot -p --default-character-set=utf8mb4 < 20260911_shipbatch_warehouse_permi.sql

SET NAMES utf8mb4;
USE `sdssys`;

-- ----------------------------------------------------------------------------
-- 1. 仓库发货管理换成独立权限串
-- ----------------------------------------------------------------------------
UPDATE `sys_menu` SET `perms` = 'order:shipbatch:warehouse',
       `remark` = '仓库发货工作台。持有本权限即可看到全部发货批次，不必再勾 order:shipbatch:all'
 WHERE `fun_code` = 'fn5103';

-- ----------------------------------------------------------------------------
-- 2. fn8043 改回原名：库管员已经不需要它了
-- ----------------------------------------------------------------------------
UPDATE `sys_menu` SET `menu_name` = '查看全部发货批次',
       `remark` = '只管「订单管理 → 发货批次」这个页面；不勾＝只看得到自己建的批次。仓库侧不需要它'
 WHERE `fun_code` = 'fn8043';

-- ----------------------------------------------------------------------------
-- 自查
-- ----------------------------------------------------------------------------
SELECT `fun_code`, `parent_id`, `menu_name`, `perms` FROM `sys_menu`
 WHERE `fun_code` IN ('fn5103', 'fn8010', 'fn8043') ORDER BY `fun_code`;

-- 哪些角色拿得到仓库发货页（这些角色现在自动看得到全部批次）
SELECT r.`role_code`, r.`role_name`, r.`shop_code`
  FROM `sys_role_menu` rm JOIN `sys_role` r ON r.`role_code` = rm.`role_code`
 WHERE rm.`fun_code` = 'fn5103' ORDER BY r.`shop_code`, r.`role_code`;
