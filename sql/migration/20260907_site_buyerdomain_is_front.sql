-- =====================================================================
-- u_s_site.buyerdomain 的语义纠正：它是「前台域名」，不是「买家后台域名」
-- =====================================================================
--
-- 库：sdsshop（ERP 那台）。可重复执行。
--
-- ⚠ 这个脚本**只改列注释，不改数据、不改结构**。不跑它，站点登记页也是好的
--   （代码那边已经改完了）；跑它只是让线上库里的注释别继续误导下一个人。
--
-- =====================================================================
-- 为什么
-- =====================================================================
--
-- 设计期的想法是：前台挂主域，buyer. 子域留给以后的「买家中心」。
-- 这一列当时的注释就是那么写的——「买家后台域名……一期只登记，买家中心未实现」。
--
-- 实际部署没这么走：主域没备案，对外服务的前台就落在了 buyer. 子域上，
-- 买家中心是它下面的几个页面，不是另一个站。康辰、统领两个站都是这样
-- （部署手册附录 C、deploy/nginx/tongling.conf）。
--
-- 而站点登记列表上那个链接原来拼的是 https://<主域名> —— 点开打不开：
-- 主域在 nginx 上连 server 块都没有，443 落到兜底块被 444 掉；
-- 浏览器在断连之前已经拿到了 buyer. 那张证书，于是页面能出来、地址栏一片红，
-- 看着像证书配错了，其实是地址就不对。现在改成由 StationSite#getFrontUrl 拼，
-- 走的就是这一列（留空则派生 buyer.<主域名>）。
--
-- ⚠ 不用改数据：两个站的 buyerdomain 都是空的，派生规则直接给出正确结果。
--   只有客户自带品牌域名、不照 buyer. 约定命名时，才需要在站点登记页填这一列。
-- =====================================================================

USE `sdsshop`;

-- MODIFY COLUMN 要把列定义整段重写一遍，漏掉的属性会被丢掉——
-- 这里和 01_schema_and_init.sql 里那一行保持逐字一致，只有 COMMENT 不同。
ALTER TABLE `u_s_site`
  MODIFY COLUMN `buyerdomain` varchar(200) DEFAULT NULL
  COMMENT '前台域名（访客看到的站）。留空则取 buyer.<主域名>。⚠ 站点登记列表上那个链接和「复制地址」由它拼，不是由主域名拼——主域一般没备案、服务器上也没配 server 块，点开打不开';


-- =====================================================================
-- 验一遍
-- =====================================================================

SELECT COLUMN_NAME AS `列`, COLUMN_COMMENT AS `注释`
  FROM information_schema.COLUMNS
 WHERE TABLE_SCHEMA = 'sdsshop'
   AND TABLE_NAME   = 'u_s_site'
   AND COLUMN_NAME  = 'buyerdomain';
