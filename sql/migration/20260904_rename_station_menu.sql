-- ============================================================================
-- fn9001 菜单改名：「站点控制台」→「独立站管理」
--
-- 背景：这个名字是内置管理台时代留下的——那会儿点进去是 ERP 自己实现的一整套站点后台
--      （/station-console/:siteCode，五个页面）。内置管理台已经整个删掉，这个菜单现在只剩
--      一张站点登记表：站点档案的增删改查，加一个跳去外部管理台的「进入管理」按钮。
--      叫「控制台」会让人以为点进去能改商品和装修，实际那些都在外部管理台里。
--      依据：docs/独立站与ERP的边界.md §7（ERP 侧是登记表不是后台入口）、§10.1 末段。
--
-- 只改显示名和备注，fun_code / path / component / 权限串一个都不动——
-- 动了那些就不是改名，是换菜单，角色授权会跟着丢。
--
-- 可重复执行。
-- ============================================================================

SET NAMES utf8mb4;
USE `sdssys`;

UPDATE sys_menu
   SET menu_name = '独立站管理',
       remark    = '独立站站点登记表'
 WHERE fun_code = 'fn9001';

-- ---- 验证：期望 fn9000(M) 独立站 → fn9001(C) 独立站管理 → 其余全是 F ----
SELECT fun_code, menu_name, menu_type, parent_id, component
  FROM sys_menu
 WHERE fun_code BETWEEN 'fn9000' AND 'fn9036'
 ORDER BY fun_code;
