-- 销售订单横向权限：业务员只看自己的单（2026-09-11）。可重复执行。
--
-- ============================================================================
-- 改了什么
-- ============================================================================
--
-- sys_menu 在「销售订单」(fn8001) 下加一个按钮级权限点：
--
--   fn8042  查看全部订单   F   order:sales:all
--
-- 语义是**能力**不是限制：
--
--   勾上   → 看得到全店所有人的销售订单（今天的行为）
--   不勾   → 只看得到 staffcode 归属于自己的单
--
-- 为什么不做成「只看自己」那种限制型权限：配错方向的后果不一样。
-- 能力型配错 → 业务员「怎么少了一半单子」，一眼看得出来；
-- 限制型配错 → 限制压根没生效，谁都不会发现。
--
-- 平台超管在代码里直接豁免，不靠这个权限点——他不做业务，只观察和维护。
--
-- ============================================================================
-- ⚠ 跑完之后行为必须和以前一模一样
-- ============================================================================
--
-- 所以第 2、3 节把这个权限**发给现有的全部角色、全部商家**。不这么做的话，
-- 脚本一落地全公司的业务员同时只剩下自己的单，看着就像订单丢了一半。
--
-- 收权是第二步，由商家管理员到「系统管理 → 角色管理」里，
-- 给业务员那类角色**取消勾选**「查看全部订单」。想什么时候收就什么时候收，
-- 可以一个角色一个角色地来。
--
-- 回滚不需要回退代码：把这个权限重新发给所有角色即可（重跑第 2 节）。
--
-- ============================================================================
-- 影响面：只挡业务员自己那几条路
-- ============================================================================
--
-- 挡：列表、详情、改单、提交、撤回、关闭、取消、删草稿
-- 不挡：审核 / 驳回 / 撤审（本来就不是下单人自己做的），
--       以及仓库发货、财务回款、生产完工、销售退货、销售补发——
--       这些岗位要按订单号取业务员的单，他们手里没有也不该有 order:sales:all，
--       挡了就是直接把发货和回款搞停。
--
-- ============================================================================
-- 执行
-- ============================================================================
--   mysql -h 127.0.0.1      -uroot -p --default-character-set=utf8mb4 < 20260911_sales_order_own_scope.sql
--   mysql -h 124.221.220.89 -uroot -p --default-character-set=utf8mb4 < 20260911_sales_order_own_scope.sql

SET NAMES utf8mb4;
USE `sdssys`;

-- ----------------------------------------------------------------------------
-- 1. 权限点
-- ----------------------------------------------------------------------------
INSERT IGNORE INTO `sys_menu`
  (`fun_code`, `parent_id`, `menu_name`, `order_num`, `path`, `component`, `query`,
   `route_name`, `is_frame`, `is_cache`, `menu_type`, `visible`, `status`, `perms`,
   `icon`, `create_by`, `create_time`, `remark`)
VALUES
  ('fn8042', 'fn8001', '查看全部订单', 10, '', '', '', '', 1, 0, 'F', '0', '0', 'order:sales:all',
   '#', 'wczladmin', sysdate(),
   '不勾选＝只看得到归属于自己的销售订单；勾选＝看得到全店的。归属认建单时的登录账号');

-- ----------------------------------------------------------------------------
-- 2. 发给现有的全部角色（跑完行为不变）
-- ----------------------------------------------------------------------------
INSERT IGNORE INTO `sys_role_menu` (`role_code`, `fun_code`)
SELECT r.`role_code`, 'fn8042' FROM `sys_role` r;

-- ----------------------------------------------------------------------------
-- 3. 挂到现有的全部商家
-- ----------------------------------------------------------------------------
-- sys_shop_menu 决定「这个商家能用哪些菜单」。少了这一步，角色上勾了也不算数：
-- selectPermissionsByMember 里 join 了 sys_shop_menu。
INSERT IGNORE INTO `sys_shop_menu`
  (`shop_code`, `fun_code`, `status`, `create_by`, `create_time`)
SELECT s.`shop_code`, 'fn8042', '0', 'wczladmin', sysdate()
  FROM (SELECT DISTINCT `shop_code` FROM `sys_shop_menu`) s;

-- ----------------------------------------------------------------------------
-- 自查
-- ----------------------------------------------------------------------------
SELECT `fun_code`, `parent_id`, `menu_name`, `menu_type`, `perms`
  FROM `sys_menu` WHERE `fun_code` = 'fn8042';

-- 期望：role_menu_rows = 角色总数，shop_menu_rows = 商家数
SELECT (SELECT count(*) FROM `sys_role`)                                   AS roles,
       (SELECT count(*) FROM `sys_role_menu`  WHERE `fun_code` = 'fn8042') AS role_menu_rows,
       (SELECT count(DISTINCT `shop_code`) FROM `sys_shop_menu`)           AS shops,
       (SELECT count(*) FROM `sys_shop_menu`  WHERE `fun_code` = 'fn8042') AS shop_menu_rows;
