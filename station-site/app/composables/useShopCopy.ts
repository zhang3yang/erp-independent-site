/**
 * 一站的购物文案。
 *
 * 传站点语言（响应式的也行——切语言时 site.lang 会变）。
 * 结果是「英文垫底 + 该语言覆盖」，所以某个语言漏翻一个键，显示的是英文原文，
 * 不是键名。
 */
export function useShopCopy(lang: MaybeRefOrGetter<string>) {
  return computed<Copy>(() => {
    const code = toValue(lang)
    return { ...EN, ...WIZARD.en, ...CUSTOMIZE.en, ...(COPY[code] || {}), ...(WIZARD[code] || {}), ...(CUSTOMIZE[code] || {}) }
  })
}

/** `fill(t.cartRemove, { name: '球阀' })` → '移除球阀' */
export function fill(template: string, vars: Record<string, string | number>) {
  return Object.entries(vars).reduce(
    (s, [k, v]) => s.replaceAll(`{${k}}`, String(v)),
    template || ''
  )
}
